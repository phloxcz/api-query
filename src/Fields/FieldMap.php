namespace Phlox\ApiQuery\Fields;

use Phlox\ApiCore\Attributes\Schema;
use Phlox\ApiCore\Documentation\SchemaBuilder;
use Phlox\ApiCore\Types\DocComment;
use Phlox\ApiCore\Types\DtoField;
use Phlox\ApiCore\Types\DtoMeta;
use Phlox\ApiCore\Types\Type;
use Phlox\ApiQuery\Attributes\Computed;
use Phlox\ApiQuery\Attributes\Field as FieldAttribute;
use Phlox\ApiQuery\Attributes\Resource;
use Phlox\EntityDatabase\Entity\Entity;
use Phlox\EntityDatabase\Metadata\EntityMeta;
use Phlox\EntityDatabase\Metadata\MetaStorage;
use Phlox\EntityDatabase\Metadata\PropertyMeta;

/**
 * Everything a query can reach, and nothing else. A name that isn't here doesn't
 * exist, as far as a client can tell, whichever part of a query it's used in.
 *
 * @phpstan-type EntityConfig array{relations: list<string>, computed: array<string, string>, resource: ?string}
 */
final class FieldMap
{
    /** @var array<string, EntityConfig> What `apiQuery.entities` says, by class */
    private static array $entities = [];

    /** @var array<string, self> Maps following `apiQuery.entities`, the same for every query of a request */
    private static array $sharedMaps = [];

    /**
     * @param array<string, Field> $fields
     * @param string|null $table Null for SQL
     * @param string|null $primaryColumn The column of a single primary key
     * @param class-string|null $entity
     * @param bool $shared Follows `apiQuery.entities`, so it's the same everywhere and can hold itself
     * @param class-string|null $resource The #[Resource] it comes from
     */
    private function __construct(
        public readonly array $fields,
        public readonly ?string $table = null,
        public readonly ?string $primaryColumn = null,
        public readonly ?string $entity = null,
        private readonly bool $shared = false,
        private readonly ?string $resource = null,
    ) {
    }

    /**
     * @param array<string, array{relations?: list<string>, computed?: array<string, string>, resource?: ?string}|object> $entities
     */
    public static function configureEntities(array $entities): void
    {
        self::$entities = [];
        self::$sharedMaps = [];
        foreach ($entities as $class => $config) {
            $config = (array) $config;
            $resource = isset($config['resource']) ? ltrim($config['resource'], '\\') : null;

            if ($resource !== null && (($config['relations'] ?? []) !== [] || ($config['computed'] ?? []) !== [])) {
                throw new \LogicException("apiQuery.entities: {$class} has a resource, which declares its own relations and computed fields, so it can't have them here.");
            }

            self::$entities[ltrim($class, '\\')] = [
                'relations' => $config['relations'] ?? [],
                'computed' => $config['computed'] ?? [],
                'resource' => $resource,
            ];
        }
    }

    /**
     * @param class-string $class A #[Resource] or an entity
     * @param list<string>|null $relations For an entity, the relations that can be reached;
     *        null means what `apiQuery.entities` says
     */
    public static function for(string $class, ?array $relations = null): self
    {
        if (self::isResource($class)) {
            if ($relations !== null) {
                throw new \LogicException("Resource {$class} declares its own relations, so none can be given for it.");
            }
            return self::forResource($class);
        }

        if (is_a($class, Entity::class, true)) {
            return self::forEntity($class, $relations);
        }

        throw new \LogicException("{$class} is neither an entity nor a class with the #[Resource] attribute.");
    }

    /**
     * Whether what a query is about exists yet. Entities are generated by a tool which
     * needs the container, so documenting them must not stop the container from compiling.
     */
    public static function canBeBuilt(string $class): bool
    {
        if (!class_exists($class)) {
            return false;
        }

        $attributes = (new \ReflectionClass($class))->getAttributes(Resource::class);

        return $attributes === [] || class_exists($attributes[0]->newInstance()->entity);
    }

    public static function isResource(string $class): bool
    {
        return class_exists($class) && (new \ReflectionClass($class))->getAttributes(Resource::class) !== [];
    }

    /**
     * Readable properties of an entity. A relation counts only when it's named:
     * `orders.items` allows `orders` and `items` under it. Without a list, the
     * relations of `apiQuery.entities` apply at every level.
     *
     * A resource configured for the entity stands for it everywhere, also where
     * it's reached through a relation of another entity.
     *
     * @param class-string $class
     * @param list<string>|null $relations
     */
    public static function forEntity(string $class, ?array $relations = null): self
    {
        $resource = self::$entities[ltrim($class, '\\')]['resource'] ?? null;
        if ($resource !== null) {
            if ($relations !== null && $relations !== []) {
                throw new \LogicException("{$class} is shown as {$resource}, which declares its own relations, so none can be given for it.");
            }
            if (!class_exists($resource) || !self::isResource($resource)) {
                throw new \LogicException("apiQuery.entities says {$class} is shown as {$resource}, which isn't a #[Resource].");
            }

            if (ltrim(self::readResource($resource)->entity, '\\') !== ltrim($class, '\\')) {
                throw new \LogicException("apiQuery.entities says {$class} is shown as {$resource}, which isn't a #[Resource] of that entity.");
            }

            return self::forResource($resource);
        }

        if ($relations === null) {
            return self::$sharedMaps[ltrim($class, '\\')] ??= self::buildForEntity($class, null);
        }

        return self::buildForEntity($class, $relations);
    }

    /**
     * @param class-string $class
     * @param list<string>|null $relations
     */
    private static function buildForEntity(string $class, ?array $relations): self
    {
        $meta = MetaStorage::get($class);
        $config = self::$entities[ltrim($class, '\\')] ?? ['relations' => [], 'computed' => [], 'resource' => null];
        $shared = $relations === null;

        // Relation => what's allowed under it
        $tree = [];
        foreach ($relations ?? $config['relations'] as $path) {
            $parts = explode('.', $path, 2);
            $tree[$parts[0]] ??= [];
            if (isset($parts[1])) {
                $tree[$parts[0]][] = $parts[1];
            }
        }

        foreach (array_keys($tree) as $name) {
            $property = $meta->byProp[$name] ?? null;
            if ($property === null || ($property->ref === null && $property->related === null)) {
                throw new \LogicException("{$class} has no relation '{$name}'.");
            }
        }

        $fields = [];
        foreach ($meta->properties as $property) {
            if (!$property->readable) {
                continue;
            }

            $isRelation = $property->ref !== null || $property->related !== null;
            if ($isRelation && !isset($tree[$property->name])) {
                continue;
            }

            $children = $shared ? null : ($tree[$property->name] ?? []);
            $fields[$property->name] = self::createField(
                $property->name,
                $property,
                $meta,
                $isRelation ? static fn(): self => self::forEntity(self::getTargetClass($property, $meta), $children) : null,
            );
        }

        foreach ($config['computed'] as $name => $type) {
            $fields[$name] = new Field($name, null, null, self::normalizeType($type), filterable: false, computed: true);
        }

        return new self($fields, $meta->table, self::findPrimaryColumn($meta), ltrim($class, '\\'), $shared);
    }

    /**
     * @param class-string $class
     */
    public static function forResource(string $class): self
    {
        $resource = self::readResource($class);
        $entity = $resource->entity;
        $meta = MetaStorage::get($entity);
        $declared = DtoMeta::getFields($class);

        // Listed first, as what's declared can replace them
        $fields = [];
        foreach (self::listResourceFields($class, $resource, $meta, $declared) as $property) {
            $fields[$property->name] = self::createField($property->name, $property, $meta, null);
        }

        foreach ($declared as $name => $dtoField) {
            $computed = self::readAttribute($class, $name, Computed::class);
            if ($computed !== null) {
                $fields[$name] = new Field(
                    $name,
                    null,
                    null,
                    self::normalizeType((string) $dtoField->type),
                    $dtoField->type->nullable,
                    filterable: false,
                    description: $dtoField->description,
                    computed: true,
                    compute: self::createCompute($class, $name, $computed),
                    schema: $dtoField->schema,
                );
                continue;
            }

            $attribute = self::readAttribute($class, $name, FieldAttribute::class) ?? new FieldAttribute();
            $propertyName = $attribute->property ?? $name;
            $property = $meta->byProp[$propertyName] ?? null;

            if ($property === null || !$property->readable) {
                throw new \LogicException("Field '{$name}' of {$class} refers to '{$propertyName}', which {$entity} has no readable property of that name.");
            }

            $isRelation = $property->ref !== null || $property->related !== null;
            $target = self::findResourceClass($dtoField->type);

            if ($isRelation && $target === null) {
                throw new \LogicException("Field '{$name}' of {$class} is a relation, so its type must be a #[Resource] or a list of them.");
            }
            if (!$isRelation && $target !== null) {
                throw new \LogicException("Field '{$name}' of {$class} holds a #[Resource], but '{$propertyName}' of {$entity} is not a relation.");
            }

            $fields[$name] = self::createField(
                $name,
                $property,
                $meta,
                $target === null ? null : static fn(): self => self::forResource($target),
                $attribute,
                $dtoField->description,
                $dtoField->schema,
            );
        }

        return new self($fields, $meta->table, self::findPrimaryColumn($meta), ltrim($entity, '\\'), resource: $class);
    }

    /**
     * @param class-string $class
     */
    private static function readResource(string $class): Resource
    {
        $attributes = (new \ReflectionClass($class))->getAttributes(Resource::class);
        if ($attributes === []) {
            throw new \LogicException("{$class} doesn't have the #[Resource] attribute.");
        }

        return $attributes[0]->newInstance();
    }

    /**
     * What `fields` of a resource name, without what the class declares itself. Every
     * mistake is an exception: a misspelled `except` would otherwise show what it should hide.
     *
     * @param class-string $class
     * @param array<string, DtoField> $declared
     * @return list<PropertyMeta>
     */
    private static function listResourceFields(string $class, Resource $resource, EntityMeta $meta, array $declared): array
    {
        if ($resource->fields === null) {
            return [];
        }

        if (is_array($resource->fields)) {
            $found = [];
            foreach ($resource->fields as $name) {
                $property = $meta->byProp[$name] ?? null;
                if ($property === null || !$property->readable) {
                    throw new \LogicException("Field '{$name}' of {$class} refers to '{$name}', which {$meta->class} has no readable property of that name.");
                }
                if ($property->ref !== null || $property->related !== null) {
                    throw new \LogicException("Field '{$name}' of {$class} is a relation, so it has to be declared in the class with the #[Resource] it's shown as.");
                }
                if (!isset($declared[$name])) {
                    $found[] = $property;
                }
            }

            return $found;
        }

        foreach ($resource->except as $name) {
            if (!isset($meta->byProp[$name])) {
                throw new \LogicException("'except' of {$class} names '{$name}', which {$meta->class} has no property of that name.");
            }
            if (isset($declared[$name])) {
                throw new \LogicException("'except' of {$class} names '{$name}', which the class declares itself.");
            }
        }

        // A property shown under another name isn't shown under its own as well
        $taken = [];
        foreach (array_keys($declared) as $name) {
            $attribute = self::readAttribute($class, $name, FieldAttribute::class);
            $taken[$attribute === null ? $name : ($attribute->property ?? $name)] = true;
        }

        return array_values(array_filter(
            $meta->properties,
            static fn(PropertyMeta $property): bool => $property->readable
                && $property->ref === null
                && $property->related === null
                && !isset($taken[$property->name])
                && !in_array($property->name, $resource->except, true),
        ));
    }

    /**
     * @param array<string, string|SqlField> $columns Field => column of the result
     * @param list<string> $searchable Fields to search in, or their columns
     */
    public static function forSql(array $columns, array $searchable = []): self
    {
        $fields = [];
        foreach ($columns as $name => $column) {
            $definition = is_string($column) ? new SqlField($column) : $column;
            $fields[$name] = new Field(
                $name,
                null,
                $definition->column,
                $definition->type,
                searchable: $definition->searchable || in_array($name, $searchable, true) || in_array($definition->column, $searchable, true),
            );
        }

        foreach ($searchable as $name) {
            if (!array_any($fields, static fn(Field $field): bool => $field->name === $name || $field->column === $name)) {
                throw new \LogicException("Searchable '{$name}' is not among the fields of the query.");
            }
        }

        return new self($fields);
    }

    /**
     * The columns of a search, by field.
     *
     * @return array<string, string>
     */
    public function getSearchColumns(): array
    {
        $columns = [];
        foreach ($this->fields as $field) {
            if ($field->searchable && $field->column !== null) {
                $columns[$field->name] = $field->column;
            }
        }

        return $columns;
    }

    /**
     * What a filter or a sort can name, including paths through relations.
     *
     * @return list<string>
     */
    public function getPaths(int $depth = 2, bool $forSort = false): array
    {
        $paths = [];

        foreach ($this->fields as $field) {
            if (!$field->filterable) {
                continue;
            }
            if ($field->relation === null) {
                if ($field->column !== null) {
                    $paths[] = $field->name;
                }
                continue;
            }
            if ($depth <= 0 || ($forSort && $field->relation->toMany)) {
                continue;
            }
            foreach ($field->relation->getTarget()->getPaths($depth - 1, $forSort) as $path) {
                $paths[] = "{$field->name}.{$path}";
            }
        }

        return $paths;
    }

    /**
     * For the description of a Query parameter.
     */
    public function describe(): string
    {
        $plain = [];
        $relations = [];
        foreach ($this->fields as $field) {
            if ($field->relation === null) {
                $plain[] = "`{$field->name}`";
            } else {
                $relations[] = "`{$field->name}`";
            }
        }

        $search = array_map(static fn(string $name): string => "`{$name}`", array_keys($this->getSearchColumns()));

        return 'Fields: ' . implode(', ', $plain) . '.'
            . ($relations === [] ? '' : ' Relations: ' . implode(', ', $relations) . '.')
            . ($search === [] ? '' : ' Search looks in: ' . implode(', ', $search) . '.');
    }

    /**
     * @return array<string, mixed>
     */
    public function toSchema(SchemaBuilder $builder): array
    {
        if ($this->entity !== null && class_exists($this->entity)) {
            $builder->addClass($this->entity);

            if ($this->resource !== null) {
                $builder->addClass($this->resource);
                $class = new \ReflectionClass($this->resource);

                return $builder->reference($class, fn(): array => self::readClassSchema($class) + $this->buildObjectSchema($builder) + self::describeClass($class));
            }

            // Relations can go in a circle here, which only a shared schema can hold
            if ($this->shared) {
                return $builder->reference(new \ReflectionClass($this->entity), fn(): array => $this->buildObjectSchema($builder));
            }
        }

        return $this->buildObjectSchema($builder);
    }

    /**
     * @param array<string, mixed>|\stdClass $item
     * @return array<string, mixed>
     */
    public static function buildPageSchema(array|\stdClass $item): array
    {
        $nullableInteger = ['type' => ['integer', 'null']];

        return [
            'type' => 'object',
            'required' => ['data', 'total', 'page', 'pageSize', 'from', 'to'],
            'properties' => [
                'data' => ['type' => 'array', 'items' => $item],
                'total' => ['type' => 'integer', 'description' => 'Rows matching the query, on all pages.'],
                'page' => $nullableInteger,
                'pageSize' => $nullableInteger,
                'from' => $nullableInteger + ['description' => 'Index of the first row on this page, from 0.'],
                'to' => $nullableInteger + ['description' => 'Index of the last row on this page, from 0.'],
            ],
        ];
    }

    /**
     * @return array<string, mixed>
     */
    private function buildObjectSchema(SchemaBuilder $builder): array
    {
        $properties = [];
        foreach ($this->fields as $field) {
            $schema = $field->relation === null
                ? self::buildValueSchema($field)
                : self::buildRelationSchema($field->relation, $builder);

            $schema = $field->schema + $schema;

            $properties[$field->name] = $field->description === '' ? ($schema ?: new \stdClass()) : ['description' => $field->description] + $schema;
        }

        return ['type' => 'object', 'properties' => $properties ?: new \stdClass()];
    }

    /**
     * @param \ReflectionClass<object> $class
     * @return array<string, mixed>
     */
    private static function readClassSchema(\ReflectionClass $class): array
    {
        $attributes = $class->getAttributes(Schema::class);

        return $attributes === [] ? [] : $attributes[0]->newInstance()->schema;
    }

    /**
     * @param \ReflectionClass<object> $class
     * @return array<string, mixed>
     */
    private static function describeClass(\ReflectionClass $class): array
    {
        $doc = new DocComment($class->getDocComment());
        $text = trim($doc->summary . "\n\n" . $doc->description);

        return $text === '' ? [] : ['description' => $text];
    }

    /**
     * @return array<string, mixed>
     */
    private static function buildRelationSchema(Relation $relation, SchemaBuilder $builder): array
    {
        $target = $relation->getTarget()->toSchema($builder);

        return $relation->toMany
            ? self::buildPageSchema($target)
            : ['anyOf' => [$target, ['type' => 'null']]];
    }

    /**
     * @return array<string, mixed>
     */
    private static function buildValueSchema(Field $field): array
    {
        $schema = match ($field->type) {
            Field::Integer => ['type' => 'integer'],
            Field::Number => ['type' => 'number'],
            Field::Boolean => ['type' => 'boolean'],
            Field::DateTime => ['type' => 'string', 'format' => 'date-time'],
            Field::Date => ['type' => 'string', 'format' => 'date'],
            Field::Time => ['type' => 'string', 'format' => 'time'],
            Field::Other => [],
            default => ['type' => 'string'],
        };

        if ($field->nullable && isset($schema['type'])) {
            $schema['type'] = [$schema['type'], 'null'];
        }

        return $schema;
    }

    /**
     * @param class-string $class
     * @return (\Closure(Entity): mixed)|null
     */
    private static function createCompute(string $class, string $field, Computed $computed): ?\Closure
    {
        if ($computed->method === null) {
            return null;
        }

        $method = (new \ReflectionClass($class))->hasMethod($computed->method)
            ? new \ReflectionMethod($class, $computed->method)
            : null;

        if ($method === null || !$method->isStatic() || !$method->isPublic()) {
            throw new \LogicException("Computed field '{$field}' of {$class} needs a public static method {$computed->method}().");
        }

        return $method->getClosure();
    }

    /**
     * @template T of object
     * @param class-string $class
     * @param class-string<T> $attribute
     * @return T|null
     */
    private static function readAttribute(string $class, string $name, string $attribute): ?object
    {
        $reflection = new \ReflectionClass($class);

        foreach ($reflection->getConstructor()?->getParameters() ?? [] as $parameter) {
            if ($parameter->getName() === $name) {
                return ($parameter->getAttributes($attribute)[0] ?? null)?->newInstance();
            }
        }

        return $reflection->hasProperty($name)
            ? ($reflection->getProperty($name)->getAttributes($attribute)[0] ?? null)?->newInstance()
            : null;
    }

    /**
     * @return class-string|null
     */
    private static function findResourceClass(Type $type): ?string
    {
        $class = match ($type->kind) {
            Type::ClassName => $type->class,
            Type::List, Type::Map => $type->items?->kind === Type::ClassName ? $type->items->class : null,
            default => null,
        };

        return $class !== null && class_exists($class) && self::isResource($class) ? $class : null;
    }

    /**
     * @param (\Closure(): self)|null $createTarget
     * @param array<string, mixed> $schema
     */
    private static function createField(
        string $name,
        PropertyMeta $property,
        EntityMeta $meta,
        ?\Closure $createTarget,
        ?FieldAttribute $attribute = null,
        string $description = '',
        array $schema = [],
    ): Field {
        $description = $description !== '' ? $description : self::cleanComment($property->comment);

        if ($createTarget !== null) {
            return new Field(
                $name,
                $property->name,
                null,
                Field::Other,
                filterable: $attribute === null || $attribute->filterable,
                relation: self::createRelation($property, $meta, $createTarget),
                description: $description,
                schema: $schema,
            );
        }

        $type = self::resolveType($property);

        return new Field(
            $name,
            $property->name,
            $property->virtual ? null : $property->col,
            $type,
            $property->nullable,
            !$property->virtual && ($attribute->searchable ?? $property->searchable),
            !$property->virtual && $type !== Field::Other && ($attribute === null || $attribute->filterable),
            null,
            $description,
            schema: $schema,
        );
    }

    /**
     * @param \Closure(): self $createTarget
     */
    private static function createRelation(PropertyMeta $property, EntityMeta $meta, \Closure $createTarget): Relation
    {
        $target = self::getTargetClass($property, $meta);
        $through = (string) $property->through;

        if ($property->related !== null) {
            return new Relation(
                true,
                $property->related,
                self::findPrimaryColumn($meta) ?? throw new \LogicException("{$meta->class} needs a single primary key for its relation '{$property->name}'."),
                $through,
                $property->condition,
                $createTarget,
            );
        }

        return new Relation(
            false,
            (string) $property->ref,
            $through,
            self::findPrimaryColumn(MetaStorage::get($target)) ?? throw new \LogicException("{$target} needs a single primary key for the relation '{$property->name}' of {$meta->class}."),
            null,
            $createTarget,
        );
    }

    /**
     * @return class-string
     */
    private static function getTargetClass(PropertyMeta $property, EntityMeta $owner): string
    {
        $class = $property->type;

        // A collection names its entity only in the generated docblock,
        // and entities generated before that have to be looked for by the table
        if ($property->related !== null) {
            $class = preg_match('/GroupedSelection<\s*\\\\?([\w\\\\]+)\s*>/', (string) $property->comment, $matches) === 1
                ? $matches[1]
                : self::findEntityOfTable($property->related, $owner)
                    ?? throw new \LogicException("Relation '{$property->name}' of {$owner->class} doesn't name its entity. Regenerate the entities with phloxcz/entity-database.");
        }

        $class = ltrim($class, '\\');
        if (!class_exists($class)) {
            throw new \LogicException("Relation '{$property->name}' refers to a class {$class} which doesn't exist.");
        }

        return $class;
    }

    /**
     * Looks among the neighbours of an entity, as they're generated side by side.
     */
    private static function findEntityOfTable(string $table, EntityMeta $owner): ?string
    {
        if (!class_exists($owner->class)) {
            return null;
        }

        $namespace = (new \ReflectionClass($owner->class))->getNamespaceName();

        foreach (glob(dirname($owner->file) . '/*.php') ?: [] as $file) {
            $class = $namespace . '\\' . basename($file, '.php');
            if (class_exists($class) && is_a($class, Entity::class, true) && MetaStorage::get($class)->table === $table) {
                return $class;
            }
        }

        return null;
    }

    private static function findPrimaryColumn(EntityMeta $meta): ?string
    {
        $keys = array_values(array_filter($meta->properties, static fn(PropertyMeta $property): bool => $property->key));

        return count($keys) === 1 ? $keys[0]->col : null;
    }

    private static function resolveType(PropertyMeta $property): string
    {
        if ($property->json !== null) {
            return Field::Other;
        }

        $class = ltrim($property->type, '\\');
        if (is_a($class, \DateTimeInterface::class, true)) {
            return match (true) {
                strtolower((string) $property->nativeType) === 'date' || $property->format === 'Y-m-d' => Field::Date,
                strtolower((string) $property->nativeType) === 'time' || $property->format === 'H:i:s' => Field::Time,
                default => Field::DateTime,
            };
        }

        return self::normalizeType($property->type);
    }

    /**
     * A type as PHP writes it, such as `?int`, to one of the constants of Field.
     */
    private static function normalizeType(string $type): string
    {
        $type = strtolower(ltrim($type, '?\\'));

        return match (true) {
            $type === 'int' || $type === 'integer' => Field::Integer,
            $type === 'float' || $type === 'double' || $type === 'number' => Field::Number,
            $type === 'bool' || $type === 'boolean' => Field::Boolean,
            $type === 'string' => Field::Text,
            in_array($type, ['datetime', 'datetimeimmutable', 'datetimeinterface'], true) => Field::DateTime,
            $type === 'date' => Field::Date,
            $type === 'time' => Field::Time,
            default => Field::Other,
        };
    }

    /**
     * A comment without docblock tags.
     */
    private static function cleanComment(?string $comment): string
    {
        return trim((string) preg_replace('/^@.*$/m', '', (string) $comment));
    }
